package io.github.maeserbern.ingredientpartygame.widget

import android.content.Context
import io.github.maeserbern.ingredientpartygame.R
import org.json.JSONObject
import java.util.GregorianCalendar
import java.util.Calendar

/** A book from the game's BOOKS table: same name, cover and Amazon link. */
data class DailyBook(val key: String, val name: String, val url: String, val coverRes: Int, val qrRes: Int)

/** One puzzle from party-game/puzzles.js ("mc" = which product, "tf" = true/false). */
data class DailyPuzzle(
    val id: Int,
    val type: String,
    val book: String,
    val statement: String,
    val options: List<String>,
    val answer: Int,
    val ingredients: List<String>,
    /** The game's weird-ingredient spotlight ("mc"); empty for "tf". */
    val spotlight: String = "",
    /** Spotlight note ("mc") or the real story behind the claim ("tf"), shown after answering. */
    val note: String = "",
) {
    val isTrueFalse: Boolean get() = type == "tf"

    /** Header of the card shown after answering, as on the game's answer screen. */
    val revealHeader: String get() = if (isTrueFalse) "THE REAL STORY" else "WEIRD INGREDIENT"

    val revealText: String get() = if (isTrueFalse || spotlight.isEmpty()) note else "$spotlight: $note"

    val answerText: String get() = options.getOrNull(answer)?.let { if (isTrueFalse) "$it." else it } ?: ""

    fun preview(count: Int): String {
        if (isTrueFalse) return statement
        val head = ingredients.take(count).joinToString(", ")
        return if (ingredients.size > count) "$head…" else head
    }

    val fullLabel: String get() = if (isTrueFalse) statement else ingredients.joinToString(", ")
}

/** res/raw/daily_puzzles.json, generated by widgets/export-widget-data.py. */
class DailyDeck(val order: IntArray, val puzzles: Map<Int, DailyPuzzle>, val books: Map<String, DailyBook>) {

    /** Everyone gets the same puzzle on the same calendar day (same rule as iOS). */
    fun puzzleForDay(day: Int): DailyPuzzle? {
        val n = order.size
        if (n == 0) return null
        val slot = ((day % n) + n) % n
        return puzzles[order[slot]]
    }

    fun bookFor(puzzle: DailyPuzzle): DailyBook? = books[puzzle.book]

    companion object {
        @Volatile private var cached: DailyDeck? = null

        fun get(context: Context): DailyDeck = cached ?: load(context).also { cached = it }

        private fun coverFor(key: String): Int = when (key) {
            "food" -> R.drawable.widget_cover_food
            "beauty" -> R.drawable.widget_cover_beauty
            "clean" -> R.drawable.widget_cover_clean
            "kids" -> R.drawable.widget_cover_kids
            "home" -> R.drawable.widget_cover_home
            else -> R.drawable.widget_cover_tp
        }

        /** The game's own QR codes (party-game/qr-<book>.svg); each opens the book's Amazon page. */
        private fun qrFor(key: String): Int = when (key) {
            "food" -> R.drawable.widget_qr_food
            "beauty" -> R.drawable.widget_qr_beauty
            "clean" -> R.drawable.widget_qr_clean
            "kids" -> R.drawable.widget_qr_kids
            "home" -> R.drawable.widget_qr_home
            else -> R.drawable.widget_qr_tp
        }

        private fun load(context: Context): DailyDeck {
            val text = context.resources.openRawResource(R.raw.daily_puzzles)
                .bufferedReader(Charsets.UTF_8).use { it.readText() }
            val json = JSONObject(text)
            val orderJson = json.getJSONArray("order")
            val order = IntArray(orderJson.length()) { orderJson.getInt(it) }
            val booksJson = json.getJSONObject("books")
            val books = booksJson.keys().asSequence().associateWith { key ->
                val b = booksJson.getJSONObject(key)
                DailyBook(key, b.getString("name"), b.getString("url"), coverFor(key), qrFor(key))
            }
            val list = json.getJSONArray("puzzles")
            val puzzles = (0 until list.length()).map { i ->
                val p = list.getJSONObject(i)
                val opts = p.getJSONArray("options")
                val ingr = p.getJSONArray("ingredients")
                DailyPuzzle(
                    id = p.getInt("id"),
                    type = p.getString("type"),
                    book = p.getString("book"),
                    statement = p.optString("statement", ""),
                    options = (0 until opts.length()).map { opts.getString(it) },
                    answer = p.getInt("answer"),
                    ingredients = (0 until ingr.length()).map { ingr.getString(it) },
                    spotlight = p.optString("spotlight", ""),
                    note = p.optString("note", ""),
                )
            }.associateBy { it.id }
            return DailyDeck(order, puzzles, books)
        }
    }
}

/** Calendar days since 2026-01-01 for the local (Gregorian) date; matches the iOS widget. */
object DailyClock {
    /** Only used by the preview test to show a fixed puzzle. */
    @Volatile var dayOverride: Int? = null

    fun today(): Int {
        dayOverride?.let { return it }
        val c = GregorianCalendar()
        return julianDay(c.get(Calendar.YEAR), c.get(Calendar.MONTH) + 1, c.get(Calendar.DAY_OF_MONTH)) -
            julianDay(2026, 1, 1)
    }

    fun julianDay(y: Int, m: Int, d: Int): Int {
        val a = (14 - m) / 12
        val yy = y + 4800 - a
        val mm = m + 12 * a - 3
        return d + (153 * mm + 2) / 5 + 365 * yy + yy / 4 - yy / 100 + yy / 400 - 32045
    }
}

/** Streak and today's answer, shared by every widget on the device. */
data class DailyState(
    val answeredDay: Int? = null,
    val choice: Int? = null,
    val lastPlayedDay: Int? = null,
    val streak: Int = 0,
    val played: Int = 0,
    val correct: Int = 0,
) {
    /** Days in a row with an answer; still shown on the day after the last play. */
    fun streakOn(day: Int): Int {
        val last = lastPlayedDay ?: return 0
        return if (day >= last && day - last <= 1) streak else 0
    }

    fun choiceOn(day: Int): Int? = if (answeredDay == day) choice else null
}

object DailyStateStore {
    private const val PREFS = "label_of_the_day"

    private fun prefs(context: Context) = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    fun load(context: Context): DailyState {
        val p = prefs(context)
        fun opt(key: String): Int? = if (p.contains(key)) p.getInt(key, 0) else null
        return DailyState(
            answeredDay = opt("answeredDay"),
            choice = opt("choice"),
            lastPlayedDay = opt("lastPlayedDay"),
            streak = p.getInt("streak", 0),
            played = p.getInt("played", 0),
            correct = p.getInt("correct", 0),
        )
    }

    fun save(context: Context, state: DailyState) {
        prefs(context).edit().apply {
            clear()
            state.answeredDay?.let { putInt("answeredDay", it) }
            state.choice?.let { putInt("choice", it) }
            state.lastPlayedDay?.let { putInt("lastPlayedDay", it) }
            putInt("streak", state.streak)
            putInt("played", state.played)
            putInt("correct", state.correct)
        }.commit()
    }

    /** Records the first answer of the day; later taps the same day change nothing. */
    fun answer(context: Context, choice: Int, day: Int): DailyState {
        val state = load(context)
        val puzzle = DailyDeck.get(context).puzzleForDay(day)
        if (state.answeredDay == day || puzzle == null || choice !in puzzle.options.indices) return state
        val next = state.copy(
            answeredDay = day,
            choice = choice,
            lastPlayedDay = day,
            streak = if (state.lastPlayedDay == day - 1) state.streak + 1 else 1,
            played = state.played + 1,
            correct = state.correct + if (choice == puzzle.answer) 1 else 0,
        )
        save(context, next)
        return next
    }
}

/** What one widget shows right now. */
data class LabelData(
    val day: Int,
    val puzzle: DailyPuzzle?,
    val book: DailyBook?,
    val choice: Int?,
    val streak: Int,
) {
    val answered: Boolean get() = choice != null
    val correct: Boolean? get() = if (choice != null && puzzle != null) choice == puzzle.answer else null

    companion object {
        fun make(context: Context): LabelData {
            val deck = DailyDeck.get(context)
            val day = DailyClock.today()
            val state = DailyStateStore.load(context)
            val puzzle = deck.puzzleForDay(day)
            return LabelData(day, puzzle, puzzle?.let { deck.bookFor(it) }, state.choiceOn(day), state.streakOn(day))
        }
    }
}
