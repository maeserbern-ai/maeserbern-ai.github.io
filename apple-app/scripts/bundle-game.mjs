// Packs the website's party-game folder into one HTML string (styles, scripts and
// pictures inlined) so the app can show the game without a network connection.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const game = join(here, "..", "..", "party-game");
if (!existsSync(join(game, "index.html"))) throw new Error("party-game folder not found next to apple-app");

const read = (f) => readFileSync(join(game, f), "utf8");
const MIME = { ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml" };
const dataUri = (f) => `data:${MIME[extname(f)]};base64,${readFileSync(join(game, f)).toString("base64")}`;

// Every picture the game can show, keyed by the path the code uses.
const pictures = [
  ...readdirSync(join(game, "covers")).map((f) => `covers/${f}`),
  ...readdirSync(game).filter((f) => /^qr-.*\.svg$/.test(f)),
  "icon-130.png"
];
const inlinePictures = (text) =>
  pictures.reduce((t, f) => t.split(`"${f}"`).join(`"${dataUri(f)}"`), text);

let html = read("index.html")
  .replace(/<link rel="(manifest|apple-touch-icon|icon)"[^>]*>\n?/g, "")
  .replace('<link rel="stylesheet" href="style.css" />', () => `<style>\n${read("style.css")}\n</style>`);
for (const js of ["puzzles.js", "glossary.js", "game.js"]) {
  html = html.replace(`<script src="${js}"></script>`, () => `<script>\n${inlinePictures(read(js))}\n</script>`);
}
for (const tag of html.match(/<script src="[^"]+"><\/script>/g) || []) throw new Error(`Script not inlined: ${tag}`);

writeFileSync(join(here, "..", "game-html.js"), `// Generated by scripts/bundle-game.mjs — do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`Bundled the party game (${Math.round(html.length / 1024)} KB).`);
