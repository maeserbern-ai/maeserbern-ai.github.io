// Packs the website's party-game folder into one HTML string (styles, scripts and
// pictures inlined) so the app can show the game without a network connection.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const game = join(here, "..", "..", "party-game");
if (!existsSync(join(game, "index.html"))) throw new Error("party-game folder not found next to apple-app");

const read = (f) => readFileSync(join(game, f), "utf8");
const MIME = { ".png": "image/png", ".jpg": "image/jpeg", ".svg": "image/svg+xml" };
const dataUri = (f) => `data:${MIME[extname(f)]};base64,${readFileSync(join(game, f)).toString("base64")}`;

// Every picture the game can show, keyed by the path the code uses.
const pictures = [
  ...readdirSync(join(game, "covers")).map((f) => `covers/${f}`),
  ...readdirSync(game).filter((f) => /^qr-.*\.svg$/.test(f)),
  "icon-130.png"
];
const inlinePictures = (text) =>
  pictures.reduce((t, f) => t.split(`"${f}"`).join(`"${dataUri(f)}"`), text);

const fontDirectory = join(here, '..', 'assets', 'fonts');
const fontCss = readFileSync(join(fontDirectory, 'fonts.css'), 'utf8').replace(
  /url\((font-\d+\.(woff2|ttf))\)/g,
  (_, file, type) => `url(data:font/${type};base64,${readFileSync(join(fontDirectory, file)).toString('base64')})`
);
const privacyLink = '<a class="native-privacy focusable" href="https://maeserbern-ai.github.io/#privacy" target="_blank" rel="noopener">Privacy Policy</a>';
let html = read("index.html")
  .replace(/<link[^>]+https:\/\/fonts\.(?:googleapis|gstatic)\.com[^>]*>\n?/g, '')
  .replace(/<link rel="(manifest|apple-touch-icon|icon)"[^>]*>\n?/g, "")
  .replace('<link rel="stylesheet" href="style.css" />', () => `<style>\n${fontCss}\n${read("style.css")}\n.native-privacy{color:#f3e9ce;text-decoration:underline;font-size:26px;display:inline-block;margin-left:24px;padding:12px 18px}\n</style>`)
  .replace('book series by Maeser</p>', `book series by Maeser ${privacyLink}</p>`)
  .replace('The TV shuffles who goes first.', 'The game shuffles who goes first.')
  .replace(/<p class="hint">Remote:[\s\S]*?<\/p>/, '<p class="hint">Tap an answer or ingredient to select it. Pass the device to the team whose turn it is. Use <b>Menu</b> to pause.</p>');
for (const js of ["puzzles.js", "glossary.js", "game.js"]) {
  let source = read(js);
  if (js === 'game.js') {
    source = source
      .replace('The TV shuffled the teams', 'The game shuffled the teams')
      .replace("Pass the remote to whoever's turn it is — or let one person be the host.", "Take turns selecting answers, or let one person host the game.");
  }
  html = html.replace(`<script src="${js}"></script>`, () => `<script>\n${inlinePictures(source)}\n</script>`);
}
for (const tag of html.match(/<script src="[^"]+"><\/script>/g) || []) throw new Error(`Script not inlined: ${tag}`);
if (/fonts\.(googleapis|gstatic)\.com/.test(html)) throw new Error('Remote font request remains in game');
if (!html.includes(privacyLink)) throw new Error('Privacy link was not inserted');

writeFileSync(join(here, "..", "game-html.js"), `// Generated by scripts/bundle-game.mjs — do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`Bundled the party game (${Math.round(html.length / 1024)} KB).`);
