import Foundation

/// A book from the game's BOOKS table (same names, covers and Amazon links).
struct DailyBook: Codable, Hashable {
    let name: String
    let title: String
    let url: URL
    let cover: String
    /// The same QR code the game shows (party-game/qr-<book>.svg); it opens `url`.
    let qr: String

    /// WidgetKit always hands a widget tap to the containing app, so the book link
    /// reaches the app as ingredientparty://book?u=<Amazon link> and the app opens
    /// it in Safari or the Amazon app right away (apple-app/plugins/with-book-links.cjs).
    var widgetLink: URL {
        var c = URLComponents()
        c.scheme = "ingredientparty"
        c.host = "book"
        c.queryItems = [URLQueryItem(name: "u", value: url.absoluteString)]
        return c.url ?? url
    }
}

/// One puzzle from party-game/puzzles.js. "mc" = which product is it (4 options),
/// "tf" = toilet-paper true/false claim (2 options).
struct DailyPuzzle: Codable, Hashable, Identifiable {
    let id: Int
    let type: String
    let book: String
    let statement: String
    let options: [String]
    let answer: Int
    let ingredients: [String]

    var isTrueFalse: Bool { type == "tf" }

    /// The first few ingredients, for the small widget.
    func preview(count: Int) -> String {
        if isTrueFalse { return statement }
        let head = ingredients.prefix(count).joined(separator: ", ")
        return ingredients.count > count ? head + "\u{2026}" : head
    }

    var fullLabel: String { isTrueFalse ? statement : ingredients.joined(separator: ", ") }
}

struct DailyDeck: Codable {
    let epoch: String
    let count: Int
    let order: [Int]
    let books: [String: DailyBook]
    let puzzles: [DailyPuzzle]

    /// Generated by widgets/export-widget-data.py; bundled with the widget.
    static let shared: DailyDeck? = {
        guard let url = Bundle.main.url(forResource: "daily", withExtension: "json")
                ?? Bundle.main.url(forResource: "daily", withExtension: "json", subdirectory: "Resources"),
              let data = try? Data(contentsOf: url) else { return nil }
        return try? JSONDecoder().decode(DailyDeck.self, from: data)
    }()

    /// Everyone gets the same puzzle on the same calendar day.
    func puzzle(forDay day: Int) -> DailyPuzzle? {
        guard count > 0, order.count == count else { return nil }
        let slot = ((day % count) + count) % count
        let index = order[slot]
        return puzzles.first { $0.id == index }
    }

    func book(for puzzle: DailyPuzzle) -> DailyBook? { books[puzzle.book] }
}

/// Calendar days since 2026-01-01 for the local date (Gregorian), so the
/// puzzle changes at local midnight and matches the Android widget.
enum DailyClock {
    static var calendar: Calendar {
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = .current
        return cal
    }

    static func day(for date: Date) -> Int {
        let c = calendar.dateComponents([.year, .month, .day], from: date)
        return julianDay(c.year ?? 2026, c.month ?? 1, c.day ?? 1) - julianDay(2026, 1, 1)
    }

    static func today() -> Int { day(for: Date()) }

    static func nextMidnight(after date: Date) -> Date {
        let start = calendar.startOfDay(for: date)
        return calendar.date(byAdding: .day, value: 1, to: start) ?? date.addingTimeInterval(86_400)
    }

    static func julianDay(_ y: Int, _ m: Int, _ d: Int) -> Int {
        let a = (14 - m) / 12
        let yy = y + 4800 - a
        let mm = m + 12 * a - 3
        return d + (153 * mm + 2) / 5 + 365 * yy + yy / 4 - yy / 100 + yy / 400 - 32045
    }
}

/// Streak and today's answer, kept in the App Group so every widget instance agrees.
struct DailyState: Codable, Equatable {
    var answeredDay: Int?
    var choice: Int?
    var lastPlayedDay: Int?
    var streak: Int = 0
    var played: Int = 0
    var correct: Int = 0

    /// Days in a row the player has answered; still shown on the day after the last play.
    func streak(on day: Int) -> Int {
        guard let last = lastPlayedDay, day >= last, day - last <= 1 else { return 0 }
        return streak
    }

    func choice(on day: Int) -> Int? { answeredDay == day ? choice : nil }
}

enum DailyStateStore {
    static let appGroup = "group.io.github.maeserbern.ingredientpartygame"
    private static let key = "labelOfTheDay.state.v1"

    private static var defaults: UserDefaults { UserDefaults(suiteName: appGroup) ?? .standard }

    static func load() -> DailyState {
        guard let data = defaults.data(forKey: key),
              let state = try? JSONDecoder().decode(DailyState.self, from: data) else { return DailyState() }
        return state
    }

    static func save(_ state: DailyState) {
        if let data = try? JSONEncoder().encode(state) { defaults.set(data, forKey: key) }
    }

    /// Records the first answer of the day. Later taps the same day change nothing.
    @discardableResult
    static func answer(choice: Int, day: Int, deck: DailyDeck? = DailyDeck.shared) -> DailyState {
        var state = load()
        guard state.answeredDay != day,
              let puzzle = deck?.puzzle(forDay: day),
              puzzle.options.indices.contains(choice) else { return state }
        state.streak = (state.lastPlayedDay == day - 1) ? state.streak + 1 : 1
        state.lastPlayedDay = day
        state.answeredDay = day
        state.choice = choice
        state.played += 1
        if choice == puzzle.answer { state.correct += 1 }
        save(state)
        return state
    }
}

/// Everything a widget view needs for one moment in time.
struct LabelEntryData: Hashable {
    let date: Date
    let day: Int
    let puzzle: DailyPuzzle?
    let book: DailyBook?
    let choice: Int?
    let streak: Int

    var answered: Bool { choice != nil }
    var correct: Bool? {
        guard let choice, let puzzle else { return nil }
        return choice == puzzle.answer
    }

    static func make(date: Date, state: DailyState = DailyStateStore.load(),
                     deck: DailyDeck? = DailyDeck.shared) -> LabelEntryData {
        let day = DailyClock.day(for: date)
        let puzzle = deck?.puzzle(forDay: day)
        return LabelEntryData(
            date: date, day: day, puzzle: puzzle,
            book: puzzle.flatMap { deck?.book(for: $0) },
            choice: state.choice(on: day), streak: state.streak(on: day)
        )
    }
}
